UPDATE `brands` SET `history` =
'L''histoire de Trinidad commence dans l''espace le plus fermé de la politique cubaine : la liste des cadeaux personnels de Fidel Castro. En 1969, trois ans après la création de Cohiba pour son usage propre, une seconde marque d''exception fut commandée dans un autre but — non plus la consommation personnelle, mais la diplomatie d''État au plus haut niveau. Le cahier des charges était précis : un cigare assez exceptionnel pour qu''en l''offrant à un chef d''État, le geste soit compris comme une marque d''estime hors du commun. Un cigare, autrement dit, qu''on ne pouvait pas acheter.

Pendant vingt-neuf ans, Trinidad fut exactement cela. Elle existait dans les caves du ministère cubain des Affaires étrangères et dans les bagages des délégations diplomatiques. Elle circulait parmi les dirigeants du mouvement des non-alignés, les chefs d''États africains nouvellement indépendants, quelques hommes d''État européens choisis. Nelson Mandela en reçut. Trinidad, c''était de la diplomatie en cèdre et en tabac.

Le format retenu pour cette période fut le Fundadores : 40 × 192 mm, près de vingt centimètres de pure Vuelta Abajo. Une expérience continue qui peut durer deux heures et traverse des phases aromatiques aussi distinctes que les actes d''une pièce. La finesse du diamètre produit un tirage plus frais et plus concentré, qui amplifie la subtilité du tabac plutôt que sa puissance. C''est un cigare qui demande une attention entière.

Le dévoilement public eut lieu en novembre 1998, lors d''un dîner de gala organisé par Davidoff à Paris. L''annonce que Trinidad serait enfin disponible causa dans le monde du cigare une sensation sans commune mesure avec l''effort de communication. Voilà une marque dont les amateurs entendaient parler depuis trois décennies — et que certains avaient goûtée en privé, par des relations diplomatiques — soudain mise sur le marché. Le Fundadores partit aussitôt, et la demande n''a jamais cessé d''excéder l''offre.

La manufacture n''alloue à Trinidad qu''une fraction de sa capacité, avec des tabacs qui passent par la même sélection rigoureuse que ceux de Cohiba. Le Reyes, petit corona ajouté à la ligne en 2003, a rendu la marque accessible dans un format court sans rien perdre du profil : racé, complexe, plus fort que son élégance ne le laisse croire. Le Coloniales, un corona extra, se tient entre les deux par la taille comme par le caractère.

Le mystère de la marque n''a pas diminué avec sa mise en vente. Savoir que Trinidad a passé ses trois premières décennies comme secret diplomatique a plutôt approfondi la dévotion de ses collectionneurs. Ce ne sont pas des fumeurs venus à elle par une critique lue quelque part : ils y sont venus parce que quelqu''un revenu d''un endroit peu ordinaire leur a dit, à voix basse, ce qu''il avait fumé.'
WHERE `name` = 'Trinidad';

-- ── Oliva ───────────────────────────────────────────────
UPDATE `brands` SET `history` =
'L''histoire de la famille Oliva commence dans la province de Pinar del Río, à Cuba, en 1886 — quand elle planta pour la première fois du tabac à l''extrémité ouest de l''île, dans ce qu''on allait appeler la Vuelta Abajo. Pendant plus de soixante ans, les Oliva cultivèrent dans cette terre rouge, y acquérant le savoir que leurs descendants emporteraient en exil.

Quand Oswaldo Oliva quitta Cuba après la révolution, il emporta des semences, un savoir agricole, et la conviction qu''un bon tabac exige des conditions précises pour donner sa mesure. Après des séjours au Honduras et à Miami, il établit en 1968 des plantations dans la vallée nicaraguayenne de Jalapa — une région où sols volcaniques, altitude et humidité constante créent ce que les dégustateurs expérimentés reconnaissent comme l''équivalent le plus proche de la Vuelta Abajo hors de Cuba.

Pendant près de trois décennies, Oliva fut le secret le moins bien gardé du métier. Si vous avez fumé un cigare premium nicaraguayen ou hondurien entre 1970 et 1995, il y a de bonnes chances que la feuille que vous teniez ait poussé sur des terres Oliva avant d''être vendue au fabricant dont le nom figurait sur la bague. Davidoff, Padrón, Ashton et des dizaines d''autres s''y sont approvisionnés. La famille vendait sans se plaindre et sans publicité : ils étaient planteurs, pas bâtisseurs de marque.

La troisième génération changea ce calcul. En 1995, convaincue que la qualité de sa feuille méritait une identité propre, elle lança Oliva Cigars. La Serie V — pour Vuelta, en hommage au Vuelta Abajo cubain — fut lancée en 2004 et devint la gamme sur laquelle la maison serait jugée.

L''avantage structurel de la maison tient à la propriété : chaque feuille qui entre dans un cigare Oliva a poussé sur des terres familiales, à Jalapa ou à Estelí. Gilberto Oliva Jr. inspecte ses plantations en personne, à cheval, à chaque saison. Ce lien direct entre la famille et le sol explique une régularité que peu d''approvisionnements sous contrat permettent.'
WHERE `name` = 'Oliva';
