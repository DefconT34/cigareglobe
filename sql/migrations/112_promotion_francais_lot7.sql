'Punch naquit en 1840, l''année même où le magazine satirique britannique du même nom publia son premier numéro. La coïncidence n''en était pas une. Manuel López, le fabricant espagnol qui créa la marque à La Havane, visait le marché anglais avec précision. Il avait compris que les acheteurs britanniques — qui dominaient déjà l''importation de cigares cubains par des maisons comme Hunters & Frankau — répondaient à l''esprit, à la référence culturelle, au sentiment qu''un produit de luxe comprenait leur monde. Nommer un cigare d''après le journal satirique le plus mordant de Londres était une déclaration d''alignement culturel. Cela fonctionna immédiatement.

Le personnage de Mr. Punch — le bouffon au nez crochu et au chapeau pointu de la tradition Punch and Judy — figure sur les bagues depuis la première année, soit cent quatre-vingts ans. Les clubs de gentlemen du Londres victorien — White''s, Brooks''s, le Reform, le Garrick — entretenaient des réserves de Punch en cave, et la marque approvisionnait des maisons royales. On a dit, un temps, que la satisfaction d''une commande longtemps attendue était l''un des sens de l''expression « pleased as Punch » — laquelle vient d''abord du personnage.

La marque a traversé les deux guerres mondiales, la nationalisation de 1959 et l''embargo américain qui l''a retirée entièrement du marché des États-Unis. Pendant tout ce temps, la manufacture — partagée avec H. Upmann à l''adresse havanaise que les deux marques occupent toujours — a maintenu les exigences qui avaient bâti la réputation d''origine.

Le profil aromatique de Punch occupe le milieu du spectre cubain avec autorité. Boisé et poivré à l''attaque, avec des notes de noix de cajou grillée et de cèdre blanc au deuxième tiers, il s''achève sur une longue finale de fruits secs et de miel discret. Ce n''est ni le plus puissant des cubains ni le plus délicat : c''est celui vers lequel on va quand on veut de la conversation et de la compagnie plutôt qu''une méditation solitaire.

Le Punch Double Corona, 49 × 194 mm, donne quatre-vingt-dix minutes qui montrent ce qu''un tabac mûr de la Vuelta Abajo peut faire avec assez de temps et de diamètre. Le Punch Punch, robusto emblématique de la maison, livre le profil entier en quarante-cinq minutes, avec une régularité qui en a fait l''un des cigares les plus commentés du catalogue havanais. Ce que la marque offre n''est pas la surprise mais la confiance — le même cigare, d''une boîte à l''autre.'
