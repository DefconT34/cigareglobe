'Hermann Dietrich Upmann arriva à La Havane en 1844 comme représentant d''une maison de banque hambourgeoise. Il n''était pas homme de tabac : il venait gérer les opérations financières de clients européens intéressés au sucre et au tabac. Mais le Cuba des années 1840 — colonie au sommet de sa vitalité commerciale, dont les plantations produisaient un tabac que l''Europe s''arrachait — changea sa trajectoire. Moins d''un an après son arrivée, Upmann avait ouvert une manufacture de cigares à côté de son comptoir. L''association parut excentrique ; elle se révéla un coup de génie commercial.

Son esprit de banquier transforma la manière dont les cigares cubains étaient vendus à l''Europe. Il fut le premier à expédier ses cigares dans des tubes d''aluminium hermétiques, qui empêchaient la perte d''humidité pendant la traversée de l''Atlantique. Il inventa la pratique des boîtes plates de cèdre scellées à la cire, qui régulaient l''hygrométrie tout en signalant l''exclusivité. Il conçut un emballage qui disait, à chaque niveau, que le contenu méritait d''être protégé. Ce sont ses codes de présentation que la profession emploie encore, cent quatre-vingts ans plus tard.

La manufacture prospéra tout au long du XIXe siècle, remportant des médailles aux expositions internationales et bâtissant une clientèle qui allait de la cour de la reine Victoria aux comptoirs de Hambourg, d''Amsterdam et de New York. La famille Upmann en garda le contrôle personnel jusqu''en 1922, quand les activités bancaires s''effondrèrent sous la pression financière de l''après-guerre. J. Frankau & Co., de Londres, racheta la marque et en maintint la qualité dans les années 1920 et 1930. Menéndez y García — l''association qui allait créer Montecristo — reprit l''affaire en 1935 et releva aussitôt les exigences de production.

La révolution de 1959 nationalisa la manufacture sans interrompre la production. Les équipes restèrent en place, l''approvisionnement continua par les mêmes fournisseurs de la Vuelta Abajo. Ce qui partit, ce fut le savoir concentré dans la famille Menéndez, qui gagna la République dominicaine — où un second H. Upmann fut créé plus tard sous Altadis.

La Magnum 46, un toro de 46 × 155 mm, offre un profil mi-corsé d''un raffinement remarquable : noisette, cèdre blanc, poivre léger, et une finale de miel qui se prolonge bien après la dernière bouffée. La Sir Winston, nommée en hommage à Churchill, est un double corona massif qui donne quatre-vingt-dix minutes d''une complexité posée. La série Connoisseur, distribuée par allocations régionales, montre que la manufacture sait produire du corsé quand elle le décide — elle préfère simplement l''art plus exigeant de l''élégance.'
