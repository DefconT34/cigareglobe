-- ── UNE ÉTYMOLOGIE AFFIRMÉE D'UN CÔTÉ, PRUDENTE DE L'AUTRE
--
-- Le français disait : « L'expression "as pleased as Punch" (ravi comme
-- Punch) S'APPLIQUAIT aux fumeurs qui avaient enfin reçu leur commande
-- après des semaines d'attente maritime. »
--
-- L'anglais dit : « became, BRIEFLY, ONE OF THE MEANINGS of the phrase
-- "pleased as Punch" ».
--
-- L'expression vient du personnage de Punch and Judy, pas du cigare. Le
-- français racontait une origine ; l'anglais rapportait un usage passager
-- parmi d'autres. C'est la version prudente qui est promue.
--
-- Troisième fois du chantier où l'anglais est PLUS RIGOUREUX que le
-- français — après Avo (« composa » contre « contribué à », migration
-- 105) et Café Crème (la couleur de la boîte, migration 107).
--
-- ── UNE FORMULE INCOMPRÉHENSIBLE ────────────────────────
--
-- « The Sir Winston, named in tribute to BOLÍVAR'S GREATEST RIVAL FOR
-- CHURCHILL'S AFFECTION ». La vitole est nommée d'après Churchill. La
-- périphrase veut dire que Churchill aimait aussi les Bolívar — elle
-- énonce une préférence classée entre deux marques, et se comprend de
-- travers. Le texte dit désormais ce qui est : nommée en hommage à
-- Churchill.
--
-- ── CE QUI PART ─────────────────────────────────────────
--
-- Du français :
--   « Punch était LE CIGARE LE PLUS VENDU EN GRANDE-BRETAGNE » ;
--   « la marque cubaine LA PLUS ACCESSIBLE sans être LA MOINS
--     HONORABLE » — deux rangs dans une seule formule.
--
-- De l'anglais :
--   « He is TOBACCO'S LONGEST-SERVING MASCOT, PREDATING EVERY CORPORATE
--     LOGO in the modern industry » — un record sans registre. Les cent
--     quatre-vingts ans, eux, se comptent et restent.
--   « the MOST DEPENDABLY PLEASURABLE » cigare ;
--   « ONE OF THE FORMAT'S FINEST EXPRESSIONS in the Cuban portfolio » ;
--   « some of the MOST UNDERRATED cigars in the Cuban portfolio » —
--     sous-estimé par qui, et mesuré comment ?
--
-- ── CE QUI EST GARDÉ ────────────────────────────────────
--
-- « Il fut LE PREMIER à expédier ses cigares dans des tubes d'aluminium
-- hermétiques » : une antériorité datée et documentée, pas un classement
-- de qualité. Et « ce sont ses codes de présentation que la profession
-- emploie encore » — une filiation observable dans n'importe quelle cave.
