'Carlos Toraño fonda en 1916 l''une des grandes maisons d''exportation de tabac de La Havane, bâtissant en quatre décennies une affaire qui reliait la feuille cubaine aux manufactures européennes dont les gammes premium dépendaient du tabac de la Vuelta Abajo. Les Toraño ont compris le tabac comme une marchandise avant de le comprendre comme un objet d''artisanat, et cette perspective commerciale — savoir lire un marché, nouer des relations, faire circuler un produit sur de longues distances — s''est révélée plus durable qu''aucun savoir de culture particulier quand la révolution mit fin à leur activité cubaine, en 1959.

Les années de diaspora suivirent un chemin partagé par beaucoup de familles de tabac cubaines : Miami d''abord, où la communauté d''exil entretenait les réseaux professionnels qui rendaient un réemploi immédiat possible, puis une recherche plus longue des conditions de culture et de l''échelle qui permettraient une vraie production, et non la seule distribution. Le Panama entra dans le calcul par une combinaison de stabilité politique, de terres disponibles et d''altitude que les Toraño jugèrent susceptible de porter la qualité qu''ils entendaient tenir.

La province de Chiriquí, dans l''ouest du pays, près de la frontière costaricaine, offre des conditions que les tabacologues trouvent plus intéressantes que la réputation agricole générale du Panama ne le laisse supposer. Les hauteurs au-dessus de Boquete, entre 1 200 et 1 800 mètres, reçoivent des pluies régulières venues à la fois du Pacifique et des Caraïbes ; cette combinaison d''humidité et d''amplitude thermique ralentit le développement de la feuille d''une manière qui concentre les composés aromatiques. Le tabac obtenu n''est pas puissant — il n''a ni le poivre et la terre du nicaraguayen, ni l''intensité chocolatée du hondurien — mais il possède une élégance retenue que des assembleurs aux ambitions précises ont su employer.

