let currentLang = 'fr';
window.currentLang = currentLang; // expose globally

function t(key){
  const lang = window.currentLang || currentLang;
  return (I18N[lang] && I18N[lang][key]) || I18N.fr[key] || key;
}
window.t = t; // expose globally

function applyLang(lang){
  currentLang = lang;
  window.currentLang = lang; // keep in sync
  const dir = I18N[lang] ? I18N[lang].dir : 'ltr';
  document.documentElement.setAttribute('lang', lang);
  document.documentElement.setAttribute('dir', dir);

  // Update all data-i18n elements (textContent)
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const val = t(key);
    // Pour les labels avec <span>*</span>, ne remplacer que le texte sans enfants
    if (el.children.length > 0) {
      // Remplacer uniquement le premier noeud texte
      for (var node of el.childNodes) {
        if (node.nodeType === 3) { node.textContent = val + ' '; break; }
      }
    } else {
      el.textContent = val;
    }
  });

  // Update data-i18n-ph (placeholders)
  document.querySelectorAll('[data-i18n-ph]').forEach(el => {
    const key = el.getAttribute('data-i18n-ph');
    el.placeholder = t(key);
  });

  // Update <option data-i18n> (select options)
  document.querySelectorAll('option[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    el.textContent = t(key);
  });

  // Dynamic content in header
  document.querySelector('.eyebrow').textContent     = t('eyebrow');
  document.querySelector('.title-sub').textContent   = t('subtitle');
  document.querySelector('[data-i18n="stat_countries"]').textContent = t('stat_countries');
  document.querySelector('[data-i18n="stat_market"]').textContent   = t('stat_market');
  document.querySelector('[data-i18n="stat_brands"]').textContent   = t('stat_brands');

  // Market button
  const mktBtn = document.getElementById('mktToggle');
  if(mktBtn) mktBtn.innerHTML = '<span style="font-size:10px">🌍</span> ' + t('markets_btn');

  // Sync all lang buttons
  document.querySelectorAll('.lang-btn,.mlang-btn').forEach(b => {
    b.classList.toggle('active', b.getAttribute('data-lang') === lang);
  });

  // Panel re-render handled by app.js patchApplyLang after this function returns

  // Invalider les caches au changement de langue
  if (typeof BRANDS_DB !== 'undefined') {
    Object.keys(BRANDS_DB).forEach(function(k){ delete BRANDS_DB[k]; });
  }
  // Invalider cache LOUNGES (objet JS) pour forcer rechargement depuis DB
  if (typeof LOUNGES !== 'undefined') {
    Object.keys(LOUNGES).forEach(function(k){ delete LOUNGES[k]; });
  }
  // Invalider aussi le cache HTTP (_cachedFetch) pour les URLs lounges et brands
  if (typeof window._loungeCache !== 'undefined') {
    var toDelete = Object.keys(window._loungeCache).filter(function(url) {
      return url.indexOf('action=lounges') !== -1 || url.indexOf('action=brand') !== -1;
    });
    toDelete.forEach(function(url) { delete window._loungeCache[url]; });
  }

  // Re-render dynamic elements if visible
  var expTitle = document.getElementById('exp-title');
  if (expTitle) expTitle.textContent = t('explorer_title');

  var expSearch = document.getElementById('exp-search');
  if (expSearch) expSearch.placeholder = t('explorer_search');

  // Re-render region/type selects
  var expRegion = document.getElementById('exp-region');
  if (expRegion) {
    expRegion.options[0].text = t('explorer_regions');
    var regionKeys = ['region_africa','region_europe','region_mideast','region_asia','region_americas','region_oceania'];
    for (var ri=1; ri<expRegion.options.length && ri-1<regionKeys.length; ri++) {
      expRegion.options[ri].text = t(regionKeys[ri-1]);
    }
  }
  var expType = document.getElementById('exp-type');
  if (expType) {
    expType.options[0].text = t('explorer_types');
    var typeKeys = ['type_lcdh','bm_distinctions','type_hotel','type_manufacture','type_cave','type_festival'];
    // Juste le premier option pour simplifier
    expType.options[0].text = t('explorer_types');
  }
  var expSort = document.getElementById('exp-sort');
  if (expSort && expSort.options.length >= 2) {
    expSort.options[0].text = t('explorer_sort_country');
    expSort.options[1].text = t('explorer_sort_rating');
  }

  // Re-render search placeholder
  var searchInput = document.getElementById('search-input');
  if (searchInput) searchInput.placeholder = t('search_ph');

  // Re-render search hint count
  var hintEl = document.getElementById('search-hint-text');
  if (hintEl) {
    var nb = Object.values(LOUNGES||{}).reduce(function(s,l){return s+(l?l.length:0);},0);
    var nbPays = Object.keys(LOUNGES||{}).length;
    if (nb > 0) hintEl.textContent = nb + ' ' + t('lounge_establish') + 's · ' + nbPays + ' ' + t('stat_countries') + ' ' + t('search_type_hint');
  }


  // Call optional hook for panel re-rendering (set by app.js)
  if (typeof window.onLangChange === 'function') window.onLangChange(lang);
}
window.applyLang = applyLang; // expose for cross-file access


